const postcss = require('postcss'); const fs = require('fs');
const SCOPE = '.gerbo-embed';
const [,, input, output] = process.argv;
if (!input) { console.error('Usage: node scripts/scope-gerbo-css.js <path/to/gerbo-ai/src/components/Dashboard.css> [out.css]'); process.exit(1); }
const src = fs.readFileSync(input, 'utf8');
const root = postcss.parse(src);

// 1) namespace keyframes so they can never clash with GerboAI/Tailwind ones
const kf = new Map();
root.walkAtRules(/keyframes$/, at => { const n = at.params.trim(); kf.set(n, 'gerbo-' + n); at.params = 'gerbo-' + n; });
root.walkDecls(/^animation(-name)?$/, d => {
  kf.forEach((to, from) => { d.value = d.value.replace(new RegExp('(^|[\\s,])' + from + '(?=[\\s,;]|$)', 'g'), '$1' + to); });
});

// 2) viewport -> container-relative sizing (the panel lives inside GerboAI's layout)
root.walkDecls(d => { if (/100vh/.test(d.value)) d.value = d.value.replace(/100vh/g, '100%'); });
// mobile drawer: pin to the embed box rather than the browser viewport
root.walkAtRules('media', at => at.walkRules(r => {
  if (/(^|,)\s*\.sidebar\s*$/.test(r.selector)) r.walkDecls('position', d => { if (d.value === 'fixed') d.value = 'absolute'; });
}));

// 3) scope every selector
let scoped = 0, retargeted = 0;
root.walkRules(rule => {
  const p = rule.parent;
  if (p && p.type === 'atrule' && /keyframes$/.test(p.name)) return;   // keyframe steps (from/to/50%)
  rule.selectors = rule.selectors.map(raw => {
    const sel = raw.trim();
    if (/^(:root|html|body)$/.test(sel)) { retargeted++; return SCOPE; }
    if (/^(html|body)\b/.test(sel)) { retargeted++; return sel.replace(/^(html|body)/, SCOPE); }
    if (/^\*/.test(sel)) { retargeted++; return SCOPE + ' ' + sel; }
    scoped++; return SCOPE + ' ' + sel;
  });
});

let out = root.toString();
fs.writeFileSync(output || 'src/gerbo/styles/gerbo-dashboard.scoped.css', '/* GENERATED by scripts/scope-gerbo-css.js from GerboAI Dashboard.css - do not edit by hand. */\n' + out);
console.log({ scoped, retargeted, keyframes: [...kf.values()] });
